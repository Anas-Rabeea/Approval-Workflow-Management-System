
--  DEPARTMENT
CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,

    manager_id BIGINT UNIQUE

    created_by VARCHAR(150) NOT NULL,
    last_modified_by VARCHAR(150),
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_date TIMESTAMP
);


-- EMPLOYEES
CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    first_name VARCHAR(150) NOT NULL,
    last_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    position VARCHAR(30) NOT NULL,

    department_id BIGINT,
    manager_id BIGINT,

    created_by VARCHAR(150) NOT NULL,
    last_modified_by VARCHAR(150),
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_date TIMESTAMP,

    CONSTRAINT fk_employee_department
        FOREIGN KEY (department_id)
        REFERENCES departments(id),

    CONSTRAINT fk_employee_manager
        FOREIGN KEY (manager_id)
        REFERENCES employees(id)
);


-- Department references Employee, so add these FKs afterward.

ALTER TABLE departments
ADD CONSTRAINT fk_department_manager
FOREIGN KEY (manager_id)
REFERENCES employees(id);

ALTER TABLE departments
ADD CONSTRAINT fk_department_approver
FOREIGN KEY (approver_id)
REFERENCES employees(id);


-- =============================================
-- 3. REQUEST ID SEQUENCE
-- =============================================

CREATE SEQUENCE request_ids
    START WITH 100
    INCREMENT BY 1;


-- =============================================
-- 4. REQUESTS
-- =============================================

CREATE TABLE requests (
    id BIGINT PRIMARY KEY DEFAULT nextval('request_ids'),

    request_number VARCHAR(50) NOT NULL UNIQUE,

    title VARCHAR(200) NOT NULL,
    description TEXT,

    request_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,

    emp_id BIGINT NOT NULL,

    submitted_at TIMESTAMP,

    created_by VARCHAR(150) NOT NULL,
    last_modified_by VARCHAR(150),
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_date TIMESTAMP,

    CONSTRAINT fk_request_employee
        FOREIGN KEY (emp_id)
        REFERENCES employees(id)
);


-- =============================================
-- 5. IT REQUEST DETAILS
-- =============================================

CREATE TABLE it_requests (
    request_id BIGINT PRIMARY KEY,

    affected_system VARCHAR(150),
    issue_category VARCHAR(50) NOT NULL,
    urgency VARCHAR(30) NOT NULL,
    attachment_url VARCHAR(500),

    CONSTRAINT fk_it_request
        FOREIGN KEY (request_id)
        REFERENCES requests(id)
        ON DELETE CASCADE
);


-- =============================================
-- 6. LEAVE REQUEST DETAILS
-- =============================================

CREATE TABLE leave_requests (
    request_id BIGINT PRIMARY KEY,

    leave_type VARCHAR(30) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    number_of_days INTEGER NOT NULL CHECK (number_of_days > 0),

    CONSTRAINT fk_leave_request
        FOREIGN KEY (request_id)
        REFERENCES requests(id)
        ON DELETE CASCADE
);


-- =============================================
-- 7. PURCHASE REQUEST DETAILS
-- =============================================

CREATE TABLE purchase_requests (
    request_id BIGINT PRIMARY KEY,

    item_name VARCHAR(200) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    estimated_price NUMERIC(12, 2) NOT NULL
        CHECK (estimated_price >= 0),
    currency VARCHAR(3) NOT NULL,
    reason TEXT,

    CONSTRAINT fk_purchase_request
        FOREIGN KEY (request_id)
        REFERENCES requests(id)
        ON DELETE CASCADE
);


-- =============================================
-- 8. APPROVAL TASKS
-- =============================================

CREATE TABLE approval_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    request_id BIGINT NOT NULL,
    approver_id BIGINT NOT NULL,

    stage_key VARCHAR(50) NOT NULL,
    stage_name VARCHAR(100) NOT NULL,
    stage_order INTEGER NOT NULL CHECK (stage_order > 0),

    attempt_number INTEGER NOT NULL DEFAULT 1
        CHECK (attempt_number > 0),

    status VARCHAR(30) NOT NULL,

    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_at TIMESTAMP,
    decided_at TIMESTAMP,

    created_by VARCHAR(150) NOT NULL,
    last_modified_by VARCHAR(150),
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_date TIMESTAMP,

    CONSTRAINT fk_task_request
        FOREIGN KEY (request_id)
        REFERENCES requests(id),

    CONSTRAINT fk_task_approver
        FOREIGN KEY (approver_id)
        REFERENCES employees(id),

    CONSTRAINT uq_request_stage_attempt
        UNIQUE (request_id, stage_order, attempt_number)
);


-- =============================================
-- 9. APPROVAL HISTORY
-- =============================================

CREATE TABLE approval_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    request_id BIGINT NOT NULL,
    approval_task_id BIGINT,
    actor_id BIGINT,

    action VARCHAR(40) NOT NULL,
    comment TEXT,

    created_by VARCHAR(150) NOT NULL,
    last_modified_by VARCHAR(150),
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_date TIMESTAMP,

    CONSTRAINT fk_history_request
        FOREIGN KEY (request_id)
        REFERENCES requests(id),

    CONSTRAINT fk_history_task
        FOREIGN KEY (approval_task_id)
        REFERENCES approval_tasks(id),

    CONSTRAINT fk_history_actor
        FOREIGN KEY (actor_id)
        REFERENCES employees(id)
);


-- =============================================
-- 10. INDEXES
-- =============================================

CREATE INDEX idx_employee_department
    ON employees(department_id);

CREATE INDEX idx_employee_manager
    ON employees(manager_id);

CREATE INDEX idx_request_employee
    ON requests(emp_id);

CREATE INDEX idx_request_status
    ON requests(status);

CREATE INDEX idx_request_monthly_limit
    ON requests(emp_id, submitted_at);

CREATE INDEX idx_task_approver_status
    ON approval_tasks(approver_id, status);

CREATE INDEX idx_task_request_stage
    ON approval_tasks(request_id, stage_order);

CREATE INDEX idx_history_request_date
    ON approval_history(request_id, created_date);
